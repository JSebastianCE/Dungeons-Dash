    FString Safe(const FString& Value)
    {
        return Value.Replace(TEXT("\r"), TEXT("\\r"))
            .Replace(TEXT("\n"), TEXT("\\n"))
            .Replace(TEXT("\t"), TEXT("\\t"));
    }

    void AppendGraph(FString& Output, UEdGraph* Graph)
    {
        if (!Graph)
        {
            return;
        }

        Output += FString::Printf(TEXT("\nGRAPH\t%s\n"), *Graph->GetName());
        for (UEdGraphNode* Node : Graph->Nodes)
        {
            if (!Node)
            {
                continue;
            }

            Output += FString::Printf(
                TEXT("NODE\t%s\t%s\t%s\n"),
                *Node->GetClass()->GetName(),
                *Node->GetName(),
                *Safe(Node->GetNodeTitle(ENodeTitleType::FullTitle).ToString()));

            for (UEdGraphPin* Pin : Node->Pins)
            {
                if (!Pin)
                {
                    continue;
                }

                FString Links;
                for (UEdGraphPin* Link : Pin->LinkedTo)
                {
                    if (!Link)
                    {
                        continue;
                    }
                    if (!Links.IsEmpty())
                    {
                        Links += TEXT(",");
                    }
                    Links += Link->GetOwningNode()->GetName();
                    Links += TEXT(".");
                    Links += Link->PinName.ToString();
                }

                Output += FString::Printf(
                    TEXT("PIN\t%s\t%s\t%s\t%s\t%s\t%s\n"),
                    Pin->Direction == EGPD_Input ? TEXT("IN") : TEXT("OUT"),
                    *Pin->PinName.ToString(),
                    *Pin->PinType.PinCategory.ToString(),
                    *Safe(Pin->DefaultValue),
                    *Safe(Pin->AutogeneratedDefaultValue),
                    *Links);
            }
        }
    }

    UEdGraphPin* FindPinByNameOrCategory(
        UEdGraphNode* Node,
        const TArray<FString>& Names,
        const EEdGraphPinDirection Direction,
        const FName Category = NAME_None)
    {
        if (!Node)
        {
            return nullptr;
        }

        for (UEdGraphPin* Pin : Node->Pins)
        {
            if (!Pin || Pin->Direction != Direction)
            {
                continue;
            }

            const FString PinName = Pin->PinName.ToString();
            for (const FString& Name : Names)
            {
                if (PinName.Equals(Name, ESearchCase::IgnoreCase))
                {
                    return Pin;
                }
            }
        }

        if (Category != NAME_None)
        {
            for (UEdGraphPin* Pin : Node->Pins)
            {
                if (Pin &&
                    Pin->Direction == Direction &&
                    Pin->PinType.PinCategory == Category)
                {
                    return Pin;
                }
            }
        }

        return nullptr;
    }

    bool NodeTitleContains(UEdGraphNode* Node, const FString& Text)
    {
        return Node &&
            Node->GetNodeTitle(ENodeTitleType::FullTitle)
                .ToString()
                .Contains(Text, ESearchCase::IgnoreCase);
    }

    UEdGraphNode* FindNodeByTitle(UEdGraph* Graph, const FString& Text)
    {
        if (!Graph)
        {
            return nullptr;
        }

        for (UEdGraphNode* Node : Graph->Nodes)
        {
            if (NodeTitleContains(Node, Text))
            {
                return Node;
            }
        }

        return nullptr;
    }

    UEdGraphPin* FindPinExact(
        UEdGraphNode* Node,
        const TCHAR* PinName,
        const EEdGraphPinDirection Direction)
    {
        if (!Node)
        {
            return nullptr;
        }

        for (UEdGraphPin* Pin : Node->Pins)
        {
            if (Pin &&
                Pin->Direction == Direction &&
                Pin->PinName == PinName)
            {
                return Pin;
            }
        }

        return nullptr;
    }

    UEdGraphPin* FindExecIn(UEdGraphNode* Node)
    {
        return FindPinExact(Node, TEXT("execute"), EGPD_Input);
    }

    UEdGraphPin* FindThenOut(UEdGraphNode* Node)
    {
        return FindPinExact(Node, TEXT("then"), EGPD_Output);
    }

    void LinkPins(UEdGraphPin* From, UEdGraphPin* To)
    {
        if (From && To && !From->LinkedTo.Contains(To))
        {
            From->MakeLinkTo(To);
        }
    }

    bool HasCodexDriftMarker(UEdGraph* Graph)
    {
        if (!Graph)
        {
            return false;
        }

        for (UEdGraphNode* Node : Graph->Nodes)
        {
            const UEdGraphNode_Comment* Comment =
                Cast<UEdGraphNode_Comment>(Node);
            if (Comment &&
                Comment->NodeComment.Contains(
                    TEXT("Codex Mario Kart Drift"),
                    ESearchCase::IgnoreCase))
            {
                return true;
            }
        }

        return false;
    }

    bool HasCommentContaining(UEdGraph* Graph, const FString& Text)
    {
        if (!Graph)
        {
            return false;
        }

        for (UEdGraphNode* Node : Graph->Nodes)
        {
            const UEdGraphNode_Comment* Comment =
                Cast<UEdGraphNode_Comment>(Node);
            if (Comment &&
                Comment->NodeComment.Contains(Text, ESearchCase::IgnoreCase))
            {
                return true;
            }
        }

        return false;
    }

    UEdGraphNode_Comment* AddComment(
        UEdGraph* Graph,
        const FString& Text,
        int32 X,
        int32 Y,
        int32 W,
        int32 H)
    {
        UEdGraphNode_Comment* Comment = NewObject<UEdGraphNode_Comment>(Graph);
        Graph->AddNode(Comment, true, false);
        Comment->NodePosX = X;
        Comment->NodePosY = Y;
        Comment->NodeWidth = W;
        Comment->NodeHeight = H;
        Comment->NodeComment = Text;
        return Comment;
    }

