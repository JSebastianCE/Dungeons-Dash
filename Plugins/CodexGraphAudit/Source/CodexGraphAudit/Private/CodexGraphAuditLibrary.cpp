    {
        return Report + TEXT("ERROR=OldActorRotationOrTickMissing; ");
    }

    UEdGraphPin* OldExecIn = FindExecIn(OldActorRotation);
    UEdGraphPin* OldThen = FindThenOut(OldActorRotation);
    UEdGraphNode* ChargeSetNode = nullptr;
    UEdGraphNode* ReadyBranchNode = nullptr;
    if (OldExecIn && OldExecIn->LinkedTo.Num() > 0)
    {
        ChargeSetNode = OldExecIn->LinkedTo[0]->GetOwningNode();
    }
    if (OldThen && OldThen->LinkedTo.Num() > 0)
    {
        ReadyBranchNode = OldThen->LinkedTo[0]->GetOwningNode();
    }

    if (!ChargeSetNode || !ReadyBranchNode)
    {
        return Report + TEXT("ERROR=DriftExecChainMissing; ");
    }

    EventGraph->Modify();
    AddComment(
        EventGraph,
        TEXT("Codex Physics Drift - mesh angular impulse, no actor transform move"),
        4520, -30, 1600, 520);

