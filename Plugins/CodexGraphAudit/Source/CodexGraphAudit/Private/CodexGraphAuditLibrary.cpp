    void EnsureMemberVariable(
        UBlueprint* Blueprint,
        FName VarName,
        FName Category,
        bool& bChanged,
        FString& Report)
    {
        if (FBlueprintEditorUtils::FindNewVariableIndex(Blueprint, VarName)
            != INDEX_NONE)
        {
            Report += FString::Printf(TEXT("%s=present; "),
                *VarName.ToString());
            return;
        }

        FEdGraphPinType PinType;
        PinType.PinCategory = Category;
        if (Category == UEdGraphSchema_K2::PC_Real)
        {
            PinType.PinSubCategory = UEdGraphSchema_K2::PC_Double;
        }
        if (FBlueprintEditorUtils::AddMemberVariable(
                Blueprint, VarName, PinType))
        {
            bChanged = true;
            Report += FString::Printf(TEXT("%s=created; "),
                *VarName.ToString());
        }
        else
        {
            Report += FString::Printf(TEXT("%s=FAILED; "),
                *VarName.ToString());
        }
    }

    void SetBoolDefault(UEdGraphNode* Node, const TCHAR* PinName, bool bValue)
    {
        if (UEdGraphPin* Pin = FindPinExact(Node, PinName, EGPD_Input))
        {
            Pin->DefaultValue = bValue ? TEXT("true") : TEXT("false");
        }
    }

    void SetRealDefault(UEdGraphNode* Node, const TCHAR* PinName, const TCHAR* Value)
    {
        if (UEdGraphPin* Pin = FindPinExact(Node, PinName, EGPD_Input))
        {
            Pin->DefaultValue = Value;
        }
    }

