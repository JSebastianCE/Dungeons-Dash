    UEdGraphNode* FindExecChainEnd(UEdGraphNode* StartNode)
    {
        UEdGraphNode* Node = StartNode;
        for (int32 Guard = 0; Node && Guard < 100; ++Guard)
        {
            UEdGraphPin* ThenPin = FindThenOut(Node);
            if (!ThenPin || ThenPin->LinkedTo.Num() == 0)
            {
                return Node;
            }

            Node = ThenPin->LinkedTo[0]->GetOwningNode();
        }

        return Node;
    }

    void InsertExecNodeAfter(UEdGraphNode* ExistingNode, UEdGraphNode* NewNode)
    {
        UEdGraphPin* ExistingThen = FindThenOut(ExistingNode);
        UEdGraphPin* NewExec = FindExecIn(NewNode);
        UEdGraphPin* NewThen = FindThenOut(NewNode);
        if (!ExistingThen || !NewExec)
        {
            return;
        }

        TArray<UEdGraphPin*> OldLinks = ExistingThen->LinkedTo;
        ExistingThen->BreakAllPinLinks();
        ExistingThen->MakeLinkTo(NewExec);

        if (NewThen)
        {
            for (UEdGraphPin* OldLink : OldLinks)
            {
                if (OldLink)
                {
                    NewThen->MakeLinkTo(OldLink);
                }
            }
        }
    }

    int32 EnsureBlueprintNodeGuids(UBlueprint* Blueprint)
    {
        if (!Blueprint)
        {
            return 0;
        }

        int32 FixedCount = 0;
        auto FixGraph = [&FixedCount](UEdGraph* Graph)
        {
            if (!Graph)
            {
                return;
            }

            for (UEdGraphNode* Node : Graph->Nodes)
            {
                if (Node && !Node->NodeGuid.IsValid())
                {
                    Node->Modify();
                    Node->CreateNewGuid();
                    ++FixedCount;
                }
            }
        };

        for (UEdGraph* Graph : Blueprint->UbergraphPages)
        {
            FixGraph(Graph);
        }
        for (UEdGraph* Graph : Blueprint->FunctionGraphs)
        {
            FixGraph(Graph);
        }

        if (FixedCount > 0)
        {
            FBlueprintEditorUtils::MarkBlueprintAsModified(Blueprint);
        }

        return FixedCount;
    }
